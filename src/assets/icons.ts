/** <i data-icon="name"></i> をインラインSVGへ置換 */
export function mountIcons(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>("i[data-icon]").forEach((el) => {
    const body = ICONS[el.dataset.icon ?? ""];
    if (!body) return;
    // "|" 区切りセグメントを要素へ変換: "<" 始まりはそのまま(rect/circle等)、それ以外は path の d 属性とする
    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("width", "1em");
    svg.setAttribute("height", "1em");
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "2");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
    svg.innerHTML = body
      .split("|")
      .map((seg) => (seg.startsWith("<") ? seg : `<path d="${seg}"/>`))
      .join("");
    el.replaceWith(svg);
  });
}